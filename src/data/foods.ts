function splitAliases(s: string): string[] {
  return s
    .toLowerCase()
    .split(/\s+/)
    .map((x) => x.trim())
    .filter(Boolean)
}

function item(
  id: string,
  name: string,
  category: string,
  emoji: string,
  aliases: string,
  form: FoodForm,
  m: Macros,
  pairId?: string,
): FoodItem {
  return {
    id,
    name,
    category,
    emoji,
    aliases: splitAliases(`${name} ${aliases} ${category}`),
    form,
    kcal: m[0],
    protein: m[1],
    fat: m[2],
    carbs: m[3],
    pairId,
  }
}

function expand(): FoodItem[] {
  const out: FoodItem[] = []
  for (const p of PAIRS) {
    const dryId = `${p.id}-dry`
    const cookedId = `${p.id}-cooked`
    out.push(item(dryId, p.name, p.category, p.emoji, `${p.aliases} сухая сухой сухие`, 'dry', p.dry, cookedId))
    out.push(
      item(
        cookedId,
        p.name,
        p.category,
        p.emoji,
        `${p.aliases} вареная варёная вареный варёный готовая`,
        'cooked',
        p.cooked,
        dryId,
      ),
    )
  }
  for (const s of [...SIMPLES, ...EXTRA_FOODS]) {
    out.push(item(s.id, s.name, s.category, s.emoji, s.aliases, s.form ?? 'as_is', s.m))
  }
  return out
}

